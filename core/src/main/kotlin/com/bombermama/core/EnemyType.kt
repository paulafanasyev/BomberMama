package com.bombermama.core

/**
 * Тип врага. Каждый тип имеет собственное поведение и характеристики.
 */
enum class EnemyType(
    val maxSpeed: Float,          // клеток в секунду
    val score: Int,               // очков за уничтожение
    val changeDirectionChance: Float, // вероятность смены направления на развилке
    val chasePlayer: Boolean      // преследует ли игрока
) {
    /** 1. Медленный враг — неуклюже бродит по полю. */
    SLOW(2.2f, 100, 0.35f, false),

    /** 2. Быстрый враг — носится по полю. */
    FAST(4.6f, 200, 0.55f, false),

    /** 3. Враг, который часто меняет направление — хаотичный. */
    CHANGER(3.2f, 150, 0.85f, false),

    /** 4. Сложный враг для поздних уровней — преследует игрока. */
    HUNTER(3.8f, 300, 0.45f, true)
}
