package com.bombermama.core

/**
 * Тип клетки игрового поля.
 */
enum class Tile {
    /** Пустой пол — по нему можно ходить. */
    FLOOR,

    /** Неразрушаемая стена. Взрыв через неё не проходит. */
    WALL,

    /** Разрушаемый блок. Взрывает, может скрывать бонус. */
    BLOCK,

    /** Выход с уровня. Появляется после уничтожения всех врагов. */
    EXIT
}
